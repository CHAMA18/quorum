/** Award recommendation as a one-click PDF (pdf-lib, no external service). */

export interface AwardPdfInput {
  tenderId: string;
  recommendation?: string;
  signedBy?: string;
  signedAt?: string;
  sha?: string;
  bids: { bidder: string; total?: number | string; verdict?: string }[];
  findings: { rule: string; severity: string; item: string }[];
}

export function wrapLine(text: string, max = 92): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let line = "";
  for (const w of words) {
    if ((line + " " + w).trim().length > max) {
      if (line) lines.push(line);
      line = w;
    } else line = (line + " " + w).trim();
  }
  if (line) lines.push(line);
  return lines.length ? lines : [""];
}

export async function renderAwardPdf(input: AwardPdfInput): Promise<Uint8Array> {
  const { PDFDocument, StandardFonts, rgb } = await import("pdf-lib");
  const doc = await PDFDocument.create();
  doc.setTitle(`Award recommendation — ${input.tenderId}`);
  doc.setAuthor("Quorum");
  const body = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.09, 0.1, 0.11);
  const muted = rgb(0.45, 0.46, 0.48);
  const A4: [number, number] = [595.28, 841.89];
  const margin = 54;
  let page = doc.addPage(A4);
  let y = A4[1] - margin;
  const room = (n: number) => { if (y - n < margin + 20) { page = doc.addPage(A4); y = A4[1] - margin; } };
  const para = (text: string, opts: { size?: number; font?: typeof body; color?: typeof ink; gap?: number } = {}) => {
    const size = opts.size ?? 10;
    for (const line of wrapLine(text)) {
      room(size + 4);
      page.drawText(line, { x: margin, y, size, font: opts.font ?? body, color: opts.color ?? ink });
      y -= size + 4;
    }
    y -= opts.gap ?? 6;
  };
  para("QUORUM — AWARD RECOMMENDATION REPORT", { size: 9, font: bold, color: muted });
  para(`Tender ${input.tenderId}`, { size: 20, font: bold, gap: 10 });
  para(`Recommendation: ${input.recommendation ?? "not stated"}`);
  para(input.signedAt ? `Signed ${input.signedAt.slice(0, 10)} by ${input.signedBy ?? "the accounting officer"}` : "Awaiting accounting officer approval — unsigned draft.");
  if (input.sha) para(`Report SHA-256: ${input.sha}`, { size: 8, color: muted });
  para("Bidders (recorded outcome)", { font: bold, gap: 4 });
  for (const b of input.bids.slice(0, 30)) para(`• ${b.bidder} — combined ${b.total ?? "—"} — ${(b.verdict ?? "").replace(/_/g, " ")}`, { size: 9.5 });
  para("Findings", { font: bold, gap: 4 });
  for (const f of input.findings.slice(0, 40)) para(`• [${f.severity}] ${f.rule} — ${f.item}`, { size: 9.5 });
  para("Generated by Quorum. The signed record in Quorum governs; this PDF is a readable copy.", { size: 8, color: muted });
  return doc.save();
}
